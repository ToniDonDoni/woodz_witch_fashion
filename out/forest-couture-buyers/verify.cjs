const {chromium}=require('playwright');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
(async()=>{
 const browser=await chromium.launch({headless:true,args:['--disable-gpu']});
 const page=await browser.newPage({viewport:{width:1388,height:1000},deviceScaleFactor:1,offline:true});
 const errors=[],requests=[];
 page.on('pageerror',e=>errors.push(String(e)));
 page.on('request',r=>{if(/^https?:/.test(r.url()))requests.push(r.url())});
 await page.goto('file://'+path.resolve(__dirname,'../../site/forest-couture-buyers/index.html'));
 await page.waitForFunction(()=>window.runway?.ready);
 await page.evaluate(()=>runway.seek(1.6));
 const first=await page.screenshot({path:path.join(__dirname,'desktop.png')});
 await page.evaluate(()=>runway.seek(4));
 await page.evaluate(()=>runway.seek(1.6));
 const second=await page.screenshot();
 assert(first.equals(second),'same time and seed must be pixel-identical');
 const state=await page.evaluate(()=>runway.state());
 assert.equal(state.cast.length,11);
 assert.equal(state.ready,true);
 assert.deepEqual(errors,[]);
 assert.deepEqual(requests,[]);
 await page.setViewportSize({width:390,height:844});
 await page.evaluate(()=>runway.seek(1.6));
 await page.screenshot({path:path.join(__dirname,'mobile.png')});
 console.log(JSON.stringify({desktop:true,mobile:true,offline:true,errors,requests,cast:state.cast}));
 await browser.close();
})().catch(e=>{console.error(e);process.exitCode=1});
